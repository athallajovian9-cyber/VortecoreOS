"""Build script for 64-bit VortecoreOS bootloader image."""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
ASM_SRC = HERE / "boot64.asm"
BIN_OUT = HERE / "boot.img"


def assemble():
    nasm = shutil.which("nasm")
    if nasm:
        print("Using NASM to compile 64-bit Long Mode bootloader...")
        subprocess.run([nasm, "-f", "bin", str(ASM_SRC), "-o", str(BIN_OUT)], check=True)
        print(f"Generated {BIN_OUT.name} ({BIN_OUT.stat().st_size} bytes)")
        return

    print("Assembling 64-bit Long Mode MBR bootloader...")
    image = bytearray(512)

    rm_code = bytes([
        0xFA, 0x31, 0xC0, 0x8E, 0xD8, 0x8E, 0xC0, 0x8E, 0xD0, 0xBC, 0x00, 0x7C, 0xFB,
        0xB4, 0x00, 0xB0, 0x03, 0xCD, 0x10,
        0xE4, 0x92, 0x0C, 0x02, 0xE6, 0x92,
        0xFA,
        0x0F, 0x01, 0x16, 0x30, 0x7C,
        0x0F, 0x20, 0xC0, 0x0C, 0x01, 0x0F, 0x22, 0xC0,
        0xEA, 0x50, 0x7C, 0x08, 0x00,
    ])
    image[:len(rm_code)] = rm_code

    gdt32_desc = (23).to_bytes(2, "little") + (0x7C38).to_bytes(4, "little")
    image[0x30:0x36] = gdt32_desc
    gdt32 = (
        b"\x00" * 8 +
        b"\xFF\xFF\x00\x00\x00\x9A\xCF\x00" +
        b"\xFF\xFF\x00\x00\x00\x92\xCF\x00"
    )
    image[0x38:0x38 + len(gdt32)] = gdt32

    pm_code = bytearray([
        0x66, 0xB8, 0x10, 0x00,
        0x8E, 0xD8,
        0x8E, 0xC0,
        0x8E, 0xD0,
        0xBC, 0x00, 0x00, 0x09, 0x00,
    ])

    pm_code.extend([
        0xBF, 0x00, 0x10, 0x00, 0x00,
        0x0F, 0x22, 0xD8,
        0x31, 0xC0,
        0xB9, 0x00, 0x10, 0x00, 0x00,
        0xF3, 0xAB,
        0xC7, 0x05, 0x00, 0x10, 0x00, 0x00, 0x03, 0x20, 0x00, 0x00,
        0xC7, 0x05, 0x00, 0x20, 0x00, 0x00, 0x03, 0x30, 0x00, 0x00,
        0xC7, 0x05, 0x00, 0x30, 0x00, 0x00, 0x03, 0x40, 0x00, 0x00,
    ])

    pm_code.extend([
        0xBF, 0x00, 0x40, 0x00, 0x00,
        0xBB, 0x03, 0x00, 0x00, 0x00,
        0xB9, 0x00, 0x02, 0x00, 0x00,
        0x89, 0x1F,
        0x81, 0xC3, 0x00, 0x10, 0x00, 0x00,
        0x83, 0xC7, 0x08,
        0xE2, 0xF1,
    ])

    pm_code.extend([
        0x0F, 0x20, 0xE0,
        0x0C, 0x20,
        0x0F, 0x22, 0xE0,
    ])

    pm_code.extend([
        0xB9, 0x80, 0x00, 0x00, 0xC0,
        0x0F, 0x32,
        0x0F, 0xBA, 0xE8, 0x08,
        0x0F, 0x30,
    ])

    pm_code.extend([
        0x0F, 0x20, 0xC0,
        0x0D, 0x00, 0x00, 0x00, 0x80,
        0x0F, 0x22, 0xC0,
    ])

    pm_code.extend([
        0x0F, 0x01, 0x16, 0xD0, 0x7C,
        0xEA, 0xF0, 0x7C, 0x08, 0x00,
    ])

    image[0x50:0x50 + len(pm_code)] = pm_code

    gdt64_desc = (23).to_bytes(2, "little") + (0x7CD8).to_bytes(4, "little")
    image[0xD0:0xD6] = gdt64_desc
    gdt64 = (
        b"\x00" * 8 +
        b"\x00\x00\x00\x00\x00\x9A\x20\x00" +
        b"\x00\x00\x00\x00\x00\x92\x00\x00"
    )
    image[0xD8:0xD8 + len(gdt64)] = gdt64

    lm_code = bytearray([
        0x66, 0xB8, 0x10, 0x00,
        0x8E, 0xD8,
        0x8E, 0xC0,
        0x8E, 0xD0,
        0x48, 0xBF, 0x6E, 0x86, 0x0B, 0x00, 0x00, 0x00, 0x00, 0x00,
    ])

    vga_text = b"=== VORTECORE OS [64-BIT x86_64 LONG MODE ACTIVE] ==="
    for c in vga_text:
        lm_code.extend([
            0x66, 0xC7, 0x07, c, 0x1F,
            0x48, 0x83, 0xC7, 0x02,
        ])

    lm_code.extend([0xF4, 0xEB, 0xFD])
    image[0xF0:0xF0 + len(lm_code)] = lm_code

    image_final = bytearray(512)
    image_final[:min(510, len(image))] = image[:min(510, len(image))]
    image_final[510] = 0x55
    image_final[511] = 0xAA

    BIN_OUT.write_bytes(image_final)
    print(f"Generated 64-bit {BIN_OUT.name} ({len(image_final)} bytes, x86_64 MBR Bootable)")


if __name__ == "__main__":
    assemble()
